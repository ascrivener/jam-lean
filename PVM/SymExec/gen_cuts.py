#!/usr/bin/env python3
"""EXPERIMENTAL (symexec): the generator interface in miniature. Emit a chain of `Cut`s for the
generated chain in <chain dir> (from its St structures and segment files), one `seg_sound` line per
segment, on the shared `Services.Bootstrap.SymExec.prog`, and their composition.
Usage: gen_cuts.py <chain dir> <k0> <every> <k1> <out.lean> <ModName>"""
import re, sys
chain_dir, k0, every, k1, out, mod = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5], sys.argv[6]
stsrc = open(f'{chain_dir}/St.lean').read()

def fields(i):
    body = re.search(rf'^structure St{i} .*? where\n(.*?)(?:\n\n|\Z)', stsrc, re.S | re.M).group(1)
    return [m.groups() for m in (re.match(r'  (\w+) : (.*)$', l) for l in body.split('\n')) if m]

def frame_upto(i):
    fr = []
    for j in range(1, i + 1):
        m = re.search(rf'^def C{j} \(a : Nat\) : Bool := (.*)$', stsrc, re.M).group(1)
        fr += [(int(a), int(b)) for a, b in re.findall(r'decide \((\d+) ≤ a ∧ a < (\d+)\)', m)]
    out = []
    for r in fr:
        if r not in out: out.append(r)
    return out

segs = []
sig = None
for i in range(k0, k1):
    s = open(f'{chain_dir}/S{i}.lean').read()
    m = re.search(r"FreeStepsH p \(refineContract env\) (\d+) ω μ x (\d+) ω' μ' x (\d+)", s)
    segs.append((i, int(m.group(1)), int(m.group(2)), int(m.group(3))))
    if sig is None: sig = re.search(r'theorem run (.*?) \(h : St\d+ ', s, re.S).group(1)
vars_, bounds, bproofs = [], [], []
for name, h, ty in re.findall(r'\((\w+) : Nat\) \((h\w+) : ([^)]*)\)', sig):
    vars_.append(name); bounds.append(int(re.search(rf'{name} < (\d+)', ty).group(1)))
    bproofs.append(f'{h}.2' if '∧' in ty else h)
vidx = {v: i for i, v in enumerate(vars_)}
sval = lambda e: f'.const {e}' if re.fullmatch(r'\d+', e.strip()) else f'.var {vidx[e.strip()]}'

def cut(i):
    regs, cells, rd, wr = [], [], [], []
    for n, t in fields(i):
        if n.startswith('hreg'):
            m = re.match(r'ω\[(\d+)\] = UInt64\.ofNat (.*)$', t); regs.append(f'({m.group(1)}, {sval(m.group(2))})')
        elif n.startswith('hm_'):
            m = re.match(r'μ\.readN (\d+) (\d+) = \[(.*)\]$', t)
            cells.append(f'(⟨none, {m.group(1)}⟩, {m.group(2)}, .const (Num.decodeLE [{m.group(3)}]))')
        elif n.startswith('hbn_'):
            m = re.match(r'μ\.readN (\d+) (\d+) = Num\.encodeLE \d+ (\w+)$', t)
            cells.append(f'(⟨none, {m.group(1)}⟩, {m.group(2)}, {sval(m.group(3))})')
        elif n.startswith('hrd_'):
            a, b = map(int, n[4:].split('_')); rd.append(f'(⟨none, {a}⟩, {b - a})')
        elif n.startswith('hw_'):
            a, b = map(int, n[3:].split('_')); wr.append(f'(⟨none, {a}⟩, {b - a})')
    fr = [f'(⟨none, {a}⟩, {b - a})' for a, b in frame_upto(i)]
    j = lambda xs: '[' + ', '.join(xs) + ']'
    return f'{{ regs := {j(regs)}\n    cells := {j(cells)}\n    rd := {j(rd)}\n    wr := {j(wr)}\n    frame := {j(fr)} }}'

cuts = list(range(k0, k1, every)) + [k1]
o = [f'''import PVM.SymExec.Cut
import Services.Bootstrap.SymExec.Prog

/-!
EXPERIMENTAL (symexec, `docs/symexec-spike.md`): cuts {cuts[0]} … {cuts[-1]} of `{chain_dir}` as
`Cut` data, one `seg_sound` line per segment, on the shared `Services.Bootstrap.SymExec.prog`.
Generated by `PVM/SymExec/gen_cuts.py`; this is the shape a generator should emit.
-/

namespace Services.Bootstrap.SymExec.{mod}

open PVM PVM.SymExec

/-- Bounds of the named naturals {", ".join(vars_)}. -/
def ub : List Nat := {bounds}
def lb : List Nat := {[0] * len(bounds)}
''']
for c in cuts:
    o.append(f'def cut{c} : Cut :=\n  {cut(c)}\n')
X = '{X : Type} {R : HostRel X} {p : ByteArray} {P : Program} [Services.Bootstrap.Code.HasCode p P]'
bvars = ' '.join(f'({v} : Nat)' for v in vars_)
for a, b in zip(cuts, cuts[1:]):
    st, en, n = segs[a - k0][1], segs[b - 1 - k0][2], sum(s[3] for s in segs[a - k0:b - k0])
    o.append(f'''theorem seg{a} {X} {bvars} (hB : BHold [{", ".join(vars_)}] ub)
    (μ₀ : Memory) (ω : Regs) (μ : Memory) (h : cut{a}.Holds [{", ".join(vars_)}] μ₀ ω μ) (x : X) :
    ∃ ω' μ', FreeStepsH p R {st} ω μ x {en} ω' μ' x {n} ∧ cut{b}.Holds [{", ".join(vars_)}] μ₀ ω' μ' :=
  seg_sound (lb := lb) (sep := []) (by decide +kernel) (Services.Bootstrap.SymExec.hyp (p := p) (P := P)) hB ⟨{", ".join("Nat.zero_le _" for _ in vars_)}, trivial⟩
    (fun _ _ => trivial) h x
''')
o.append(f'end Services.Bootstrap.SymExec.{mod}\n')
open(out, 'w').write('\n'.join(o))
print(out, cuts)
