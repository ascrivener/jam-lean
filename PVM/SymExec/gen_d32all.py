"""Generate Services/Bootstrap/SymExec/Dec32All.lean: the 12 range theorems of Dec32.lean in one
uniform shape (`fin_<lo>`), and `dec32` for every u32 by cases on the range."""
import sys
R = [(0, 1), (1, 10), (10, 100), (100, 1000), (1000, 10000), (10000, 100000), (100000, 1000000),
     (1000000, 10000000), (10000000, 100000000), (100000000, 1000000000), (1000000000, 2147483648),
     (2147483648, 4294967296)]
STEPS = 123

HYPS = '''{X : Type} {R : HostRel X} {p : ByteArray} {P : Program} [HasCode p P] [HasCodeF p P]
    (x : X) (ω : Regs) (μ : Memory) (y sp v F ret v5 v6 : Nat)
    (hy : HY) (hsp : 2147484248 ≤ sp ∧ sp < 4294967296)
    (hv : v < 4294967292) (hF : F < 4294967296) (hret : 2 ≤ ret ∧ ret < 2807) (h5 : v5 < 18446744073709551616)
    (h6 : v6 < 18446744073709551616)
    (r0 : ω[0] = UInt64.ofNat ret) (r1 : ω[1] = UInt64.ofNat sp) (r5 : ω[5] = UInt64.ofNat v5)
    (r6 : ω[6] = UInt64.ofNat v6) (r7 : ω[7] = UInt64.ofNat v) (r8 : ω[8] = UInt64.ofNat F)
    (hY : μ.readN v 4 = encodeLE 4 y) (ht : Table μ)
    (hrv : ∀ t, v ≤ t → t < v + 4 → μ.readable t = true)
    (hrt : ∀ t, 70844 ≤ t → t < 71044 → μ.readable t = true)
    (hw : ∀ t, sp - 72 ≤ t → t < sp → μ.writable t = true) (hs : v + 4 ≤ sp - 72 ∨ sp ≤ v) :
    ∃ ω' μ', FreeStepsH p R 68146 ω μ x 61857 ω' μ' x STEPS ∧ (decB y).length ≤ 10 ∧
      ω'[0] = UInt64.ofNat 2802 ∧ ω'[1] = UInt64.ofNat (sp - 72) ∧ ω'[7] = UInt64.ofNat F ∧
      ω'[11] = UInt64.ofNat (sp - 24 - (decB y).length) ∧ ω'[12] = UInt64.ofNat (decB y).length ∧
      μ'.readN (sp - 24 - (decB y).length) (decB y).length = decB y ∧
      μ'.readN (sp - 8) 8 = encodeLE 8 ret ∧ μ'.readN (sp - 16) 8 = encodeLE 8 v5 ∧
      μ'.readN (sp - 24) 8 = encodeLE 8 v6 ∧
      (∀ t, t < two32 → (t < sp - 72 ∨ sp ≤ t) → μ'.read t = μ.read t) ∧ μ'.pages = μ.pages'''.replace('STEPS', str(STEPS))
ARGS = 'x ω μ y sp v F ret v5 v6 HYV hsp hv hF hret h5 h6 r0 r1 r5 r6 r7 r8 hY ht hrv hrt hw hs'

def ndig(lo):
    return max(1, len(str(lo))) if lo < 2147483648 else 10

out = ['''import Services.Bootstrap.SymExec.Dec32

/-!
# u32 `Display`, every u32

`Dec32.lean` runs `<u32 as Display>::fmt` from its entry 68146 to its call of `pad_integral`
(61857) in twelve ranges of y. Here every range is put in one shape, and `dec32` covers every
u32: the digit octets on the stack at sp − 24 − n are `decB y`, the octets of `Nat.repr y`
(GP Appendix B's logging text; `repr_utf8`), with n = their count in ω₁₂ and their address in
ω₁₁. Generated by PVM/SymExec/gen_d32all.py.
-/

namespace Services.Bootstrap.SymExec.Dec32

open PVM PVM.SymExec Num Services.Bootstrap.Code Services.Bootstrap.CodeF
''']
import re
D32 = open(sys.argv[1].replace('Dec32All', 'Dec32')).read()
def ncells(lo):
    m = re.search(r'def T_%d : Spec :=\n.*\n    cells := (.*) \}\n' % lo, D32)
    return m.group(1).count('({ base :=')
for lo, hi in R:
    n = ndig(lo)
    hy = f'{lo} ≤ y ∧ y < {hi}'
    out.append(f'''/-- The range {lo} ≤ y < {hi} ({n} digits) in the shape of `dec32`. -/
theorem fin_{lo} {HYPS.replace('HY', hy)} := by
  obtain ⟨ω', μ', run, hr, hc, hfr, hpg⟩ := run_{lo} (R := R) (p := p) (P := P) {ARGS.replace('HYV', 'hy')}
  have hd := digits_{lo} hy hsp ht hc
  have hl : (decB y).length = {n} := by rw [← hd, Memory.length_readN]
  obtain ⟨g0, g1, g7, g11, g12, -⟩ := hr
  obtain ⟨{', '.join('-' for _ in range(ncells(lo)))}, s8, s16, s24, -⟩ := hc
  simp only [T_{lo}, SVal.eval, Aff.eval, vals_{lo}, List.getD_cons_succ, List.getD_cons_zero] at s8 s16 s24
  simp only [T_{lo}, SVal.eval, Aff.eval, vals_{lo}, List.getD_cons_succ, List.getD_cons_zero] at g0 g1 g7 g11 g12
  rw [hl]
  refine ⟨ω', μ', run.mono (by decide), by decide, g0, ?_, g7, ?_, g12, by rw [show sp - 24 - {n} = sp - {24 + n} by omega]; exact hd,
    by rw [show sp - 8 = ((sp : Int) + -8).toNat by omega]; exact s8,
    by rw [show sp - 16 = ((sp : Int) + -16).toNat by omega]; exact s16,
    by rw [show sp - 24 = ((sp : Int) + -24).toNat by omega]; exact s24, hfr, hpg⟩
  · rw [show sp - 72 = ((sp : Int) + -72).toNat by omega]; exact g1
  · rw [show sp - 24 - {n} = ((sp : Int) + -{24 + n}).toNat by omega]; exact g11
''')
cases = ' ∨ '.join(f'({lo} ≤ y ∧ y < {hi})' for lo, hi in R)
pats = ' | '.join('h' for _ in R)
out.append(f'''/-- **u32 `Display`, every u32**: from `<u32 as Display>::fmt`'s entry 68146, with ω₇ = v the
    address of the u32 y and ω₈ = F the `Formatter`, the run reaches the call of `pad_integral`
    (61857) within {STEPS} steps with the decimal digits of y, `decB y` = `(Nat.repr y).toUTF8`,
    on the stack at sp − 24 − n, their address in ω₁₁ and their count n in ω₁₂, ω₇ = F, the return
    address 2802 in ω₀ and the frame sp − 72 in ω₁. Memory changes only in sp − 72 … sp. -/
theorem dec32 {HYPS.replace('(hy : HY)', '(hy : y < 4294967296)')} := by
  rcases (show {cases} by omega) with {pats}
''')
for lo, hi in R:
    out.append(f'  · exact fin_{lo} (R := R) (p := p) (P := P) {ARGS.replace("HYV", "h")}\n')
out.append('\nend Services.Bootstrap.SymExec.Dec32\n')
open(sys.argv[1], 'w').write('\n'.join(out[:1]) + '\n' + '\n'.join(out[1:]))
