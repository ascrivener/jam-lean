#!/usr/bin/env python3
"""EXPERIMENTAL (symexec): emit a shared executor `Prog` of a binary from one or more code-facts
modules (their `d_i`, `bs_i`, `jte_k` and `jts` lemmas) and the proof of `ProgHyp` from them.

Usage: gen_prog.py <out.lean> <module namespace> <def suffix> <Namespace>[@<Module>]=<file>[,<file>...] ...

Each source is a namespace and the files holding its lemmas (e.g.
`Services.Bootstrap.CodeA=Services/Bootstrap/CodeA/L0.lean,...`). Facts at the same index are
taken from the first source that has them. The theorems take every source's instance class.
With `@<Module>` (e.g. `Services.Bootstrap.CodeA@Services.Bootstrap.CodeAAll=...`), the output
imports that aggregate module instead of the individual files, so that regenerating the code facts
into different files does not break it."""
import re, sys, glob
out, mns, suf = sys.argv[1], sys.argv[2], sys.argv[3]
srcs = []
for a in sys.argv[4:]:
    ns, files = a.split('=', 1)
    ns, _, mod = ns.partition('@')
    fs = []
    for pat in files.split(','):
        fs += sorted(glob.glob(pat))
    srcs.append((ns, fs, mod))

ins, bs, jt, jsize, classes, imports = {}, {}, {}, None, [], []
for ns, fs, mod in srcs:
    for f in fs:
        code = open(f).read()
        imports.append(mod or f[:-5].replace('/', '.'))
        for c in re.findall(r'\[h : (Has\w+) p P\]', code):
            if c not in classes: classes.append(c)
        for a, b, c in re.findall(r'^theorem d_(\d+) .*?P\.decode \d+ = some (.*?) ∧ P\.next \d+ = (\d+) ∧', code, re.M):
            ins.setdefault(int(a), (b, int(c), ns))
        for a, b in re.findall(r'^@\[pvm_code\] theorem bs_(\d+) .*?P\.isBlockStart \d+ = (true|false) :=', code, re.M):
            bs.setdefault(int(a), (b, ns))
        for a, b in re.findall(r'^@\[pvm_code\] theorem jte_(\d+) .*?getD \d+ 0 = (\d+) :=', code, re.M):
            jt.setdefault(int(a), (int(b), ns))
        m = re.search(r'theorem jts .*?P\.jumpTable\.size = (\d+)', code)
        if m and jsize is None: jsize = (int(m.group(1)), ns)

def items(d): return sorted(d.items())

def tree(es, val):
    if not es: return '.leaf'
    m = len(es) // 2
    return f'(.node {tree(es[:m], val)}\n  {es[m][0]} {val(es[m][1])} {tree(es[m+1:], val)})'

def proof(es, name):
    if not es: return 'trivial'
    m = len(es) // 2
    k, v = es[m]
    return f'⟨{v[-1]}.{name}_{k} (p := p) (P := P), {proof(es[:m], name)}, {proof(es[m+1:], name)}⟩'

sys.setrecursionlimit(100000)
I, B, J = items(ins), items(bs), items(jt)
insts = ' '.join(f'[{c} p P]' for c in classes)
cls = ' '.join(f'{ns}' for ns, _, _ in srcs)
o = f'''/-
  GENERATED by `PVM/SymExec/gen_prog.py`. Do not edit by hand.
-/
import PVM.SymExec.Check
{chr(10).join("import " + m for m in dict.fromkeys(imports))}

/-!
EXPERIMENTAL (symexec, `docs/symexec-spike.md`): the executor's view of the code facts of
{", ".join("`" + ns + "`" for ns, _, _ in srcs)}: every instruction fact ({len(I)}), block start ({len(B)})
and jump-table entry ({len(J)}) as search trees, and `hyp{suf}`, their `ProgHyp`, from the code facts'
lemmas.
-/

namespace {mns}

open PVM PVM.SymExec {cls}

set_option maxRecDepth 100000

set_option maxHeartbeats 0 in
def code{suf} : NTree (Instr × Nat) := {tree(I, lambda v: f"({v[0]}, {v[1]})")}

set_option maxHeartbeats 0 in
def bs{suf} : NTree Bool := {tree(B, lambda v: v[0])}

set_option maxHeartbeats 0 in
def jt{suf} : NTree Nat := {tree(J, lambda v: str(v[0]))}

/-- The code for the executor. -/
def prog{suf} : Prog := {{ code := code{suf}, bs := bs{suf}, jt := jt{suf}, jsize := {jsize[0]} }}

set_option maxHeartbeats 0 in
theorem hyp_code{suf} {{p : ByteArray}} {{P : Program}} {insts} :
    code{suf}.All (fun pc e => deblob p pc = some P ∧ P.decode pc = some e.1 ∧ P.next pc = e.2 ∧
      P.blockCost (P.blockStartOf pc) ≤ stepCostCap) :=
  {proof(I, 'd')}

set_option maxHeartbeats 0 in
theorem hyp_bs{suf} {{p : ByteArray}} {{P : Program}} {insts} :
    bs{suf}.All (fun n b => P.isBlockStart n = b) :=
  {proof(B, 'bs')}

set_option maxHeartbeats 0 in
theorem hyp_jt{suf} {{p : ByteArray}} {{P : Program}} {insts} :
    jt{suf}.All (fun k t => P.jumpTable.getD k 0 = t) :=
  {proof(J, 'jte')}

/-- The facts of `prog{suf}` hold of the blob `p` deblobs to. -/
theorem hyp{suf} {{p : ByteArray}} {{P : Program}} {insts} : ProgHyp p P prog{suf} :=
  ⟨hyp_code{suf}, hyp_bs{suf}, hyp_jt{suf}, {jsize[1]}.jts (p := p) (P := P)⟩

end {mns}
'''
open(out, 'w').write(o)
print(out, len(I), len(B), len(J), classes)
