#!/usr/bin/env python3
"""EXPERIMENTAL (symexec): emit the shared executor `Prog` of a binary from its code-facts file
(the `d_i`, `bs_i`, `jte_k` and `jts` lemmas) and the proof of `ProgHyp` from them.
Usage: gen_prog.py <Code.lean> <code namespace> <out.lean> <module namespace>"""
import re, sys
src, cns, out, mns = sys.argv[1:5]
code = open(src).read()
ins = [(int(a), b, int(c)) for a, b, c in
       re.findall(r'^theorem d_(\d+) .*?P\.decode \d+ = some (.*?) ∧ P\.next \d+ = (\d+) ∧', code, re.M)]
bs = [(int(a), b) for a, b in re.findall(r'^@\[pvm_code\] theorem bs_(\d+) .*?P\.isBlockStart \d+ = (true|false) :=', code, re.M)]
jt = [(int(a), int(b)) for a, b in re.findall(r'^@\[pvm_code\] theorem jte_(\d+) .*?getD \d+ 0 = (\d+) :=', code, re.M)]
jsize = int(re.search(r'theorem jts .*?P\.jumpTable\.size = (\d+)', code).group(1))
ins.sort(); bs.sort(); jt.sort()

def tree(es, val):
    if not es: return '.leaf'
    m = len(es) // 2
    return f'(.node {tree(es[:m], val)}\n  {es[m][0]} {val(es[m])} {tree(es[m+1:], val)})'

def proof(es, name):
    if not es: return 'trivial'
    m = len(es) // 2
    return f'⟨{name}_{es[m][0]} (p := p) (P := P), {proof(es[:m], name)}, {proof(es[m+1:], name)}⟩'

sys.setrecursionlimit(100000)
o = f'''/-
  GENERATED by `PVM/SymExec/gen_prog.py` from `{src}`. Do not edit by hand.
-/
import PVM.SymExec.Check
import {cns}

/-!
EXPERIMENTAL (symexec, `docs/symexec-spike.md`): the executor's view of the code facts of
`{cns}`: every instruction fact ({len(ins)}), block start ({len(bs)}) and jump-table entry
({len(jt)}) as search trees, and `hyp`, their `ProgHyp`, from the code facts' lemmas.
-/

namespace {mns}

open PVM PVM.SymExec {cns}

set_option maxRecDepth 100000

def code : NTree (Instr × Nat) := {tree(ins, lambda e: f"({e[1]}, {e[2]})")}

def bs : NTree Bool := {tree(bs, lambda e: e[1])}

def jt : NTree Nat := {tree(jt, lambda e: str(e[1]))}

/-- The code of `{cns}` for the executor. -/
def prog : Prog := {{ code := code, bs := bs, jt := jt, jsize := {jsize} }}

theorem hyp_code {{p : ByteArray}} {{P : Program}} [HasCode p P] :
    code.All (fun pc e => deblob p pc = some P ∧ P.decode pc = some e.1 ∧ P.next pc = e.2 ∧
      P.blockCost (P.blockStartOf pc) ≤ stepCostCap) :=
  {proof(ins, 'd')}

theorem hyp_bs {{p : ByteArray}} {{P : Program}} [HasCode p P] :
    bs.All (fun n b => P.isBlockStart n = b) :=
  {proof(bs, 'bs')}

theorem hyp_jt {{p : ByteArray}} {{P : Program}} [HasCode p P] :
    jt.All (fun k t => P.jumpTable.getD k 0 = t) :=
  {proof(jt, 'jte')}

/-- The facts of `prog` hold of the blob `p` deblobs to. -/
theorem hyp {{p : ByteArray}} {{P : Program}} [HasCode p P] : ProgHyp p P prog :=
  ⟨hyp_code, hyp_bs, hyp_jt, jts (p := p) (P := P)⟩

end {mns}
'''
open(out, 'w').write(o)
print(out, len(ins), len(bs), len(jt))
