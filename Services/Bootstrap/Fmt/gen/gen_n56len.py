"""Generates N56Len.lean: 56340's length computation (56921 -> 57327) in chunks, each a pvm_go run
whose live registers are given by their bounds (bounds.py), composed into `n56_len`."""
import re, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dis import ins

START, END, CH = 56921, 57327, 16

def p2(b): return (1 << b.bit_length()) - 1

# walk once: pcs, and the bounds before each instruction
pcs, bnds, stores = [], [], []
B = {}
a = START
while a != END:
    t, nx = ins[a]
    pcs.append(a); bnds.append(dict(B))
    m = re.match(r'\(\.(\w+) \(\.(\w+)\)(.*)\)', t)
    kind, op, args = m.group(1), m.group(2), [int(x) for x in m.group(3).split()]
    def g(r): return B.get(r)
    if kind == 'twoRegImm':
        d, s, i = args
        if op.startswith('store'): stores.append((a, i))
        elif op.startswith('load'): B.pop(d, None)
        elif op in ('setLtUImm', 'setGtUImm'): B[d] = 1
        elif op == 'xorImm':
            if g(s) is not None: B[d] = max(p2(g(s)), p2(i))
            else: B.pop(d, None)
        elif op == 'andImm': B[d] = i if g(s) is None else min(i, g(s))
        elif op == 'addImm64' and g(s) is not None and i < 2**32: B[d] = g(s) + i
        else: B.pop(d, None)
    elif kind == 'threeReg':
        x, y, d = args
        if op == 'cmovNz' and g(x) is not None and g(d) is not None: B[d] = max(g(x), g(d))
        elif op in ('or', 'xor') and g(x) is not None and g(y) is not None: B[d] = max(p2(g(x)), p2(g(y)))
        else: B.pop(d, None)
    elif kind == 'twoReg':
        d, s = args
        if g(s) is not None: B[d] = g(s)
        else: B.pop(d, None)
    elif kind == 'regImm' and op == 'loadImm': B[args[0]] = args[1]
    else: raise Exception(t)
    a = nx
pcs.append(END); bnds.append(dict(B))
N = len(pcs) - 1
# one bitwise lemma (operands ≤ 31) covers every step: round the bounds up to 31
bnds = [{r: (31 if b <= 31 else b) for r, b in bd.items()} for bd in bnds]
cuts = list(range(0, N, CH)) + [N]
# registers 5, 7, 8 hold addresses at the end; drop them from the final bounds
bnds[N] = {r: b for r, b in bnds[N].items() if r not in (5, 7, 8)}
assert all(r != 7 for r in bnds[N]), bnds[N]

def hyps(bd, pre):
    return ''.join(f' ({pre}{r} : ω[{r}].toNat ≤ {b})' for r, b in sorted(bd.items()))

def concl(bd):
    return ''.join(f' ∧ ω\'[{r}].toNat ≤ {b}' for r, b in sorted(bd.items()))

hdr = '''import Services.Bootstrap.Fmt.Tac

/-!
# `56340`: the length of the name without its trailing NULs (56921 → 57327)

After the 32 octet checks (`N56Steps`), 56340 computes, in about 130 straight-line ALU and
conditional-move instructions over 0/1 flags (each octet tested against 0, some read back from the
stack slots sp + 0 … sp + 192), the length it passes to `core::str::from_utf8` (60681) in ω₉. Only
its bound is stated: ω₉ ≤ 32, with ω₇ = sp + 200 (the result), ω₈ = ω₅ = the name's address a.
Generated by `gen/gen_n56len.py`: one `pvm_go` run per chunk of at most 16 instructions, the live
registers given by their bounds (`gen/bounds.py`), composed in `n56_len`.
-/

namespace Services.Bootstrap.Fmt

open PVM Services.Bootstrap Services.Bootstrap.Code Services.Bootstrap.CodeF

set_option maxHeartbeats 8000000
set_option maxRecDepth 100000

variable {X : Type} {R : HostRel X}

theorem n56l_ofNat {a c : Nat} (h : a ≤ c) (hc : c < 18446744073709551616) : (UInt64.ofNat a).toNat ≤ c := by
  simp only [UInt64.toNat_ofNat']; exact Nat.le_trans (Nat.mod_le _ _) h

theorem n56l_ite {p : Prop} [Decidable p] {a b c : Nat} (ha : a ≤ c) (hb : b ≤ c) : (if p then a else b) ≤ c := by
  split <;> assumption

theorem n56l_mod {a c m : Nat} (h : a ≤ c) : a % m ≤ c := Nat.le_trans (Nat.mod_le _ _) h

theorem n56l_add {a k c : Nat} (h : a ≤ c - k) (hk : k ≤ c) : a + k ≤ c := by omega

theorem n56l_bw (f : Bool → Bool → Bool) (hf : f false false = false) {a b c : Nat} (ha : a ≤ 31)
    (hb : b ≤ 31) (hc : 31 ≤ c) : Exec.bitwise f a b ≤ c := by
  suffices Exec.bitwise f a b < 2 ^ 5 by omega
  apply Nat.lt_pow_two_of_testBit
  intro i hi
  have ha' : a.testBit i = false :=
    Nat.testBit_lt_two_pow (Nat.lt_of_lt_of_le (show a < 2 ^ 5 by omega) (Nat.pow_le_pow_right (by decide) hi))
  have hb' : b.testBit i = false :=
    Nat.testBit_lt_two_pow (Nat.lt_of_lt_of_le (show b < 2 ^ 5 by omega) (Nat.pow_le_pow_right (by decide) hi))
  simp only [Exec.bitwise, Num.testBit_ofBits, Num.bit_eq_testBit, ha', hb', hf, Bool.and_false]

theorem n56l_or {a b c : Nat} (ha : a ≤ 31) (hb : b ≤ 31) (hc : 31 ≤ c) :
    Exec.bitwise (· || ·) a b ≤ c := n56l_bw _ rfl ha hb hc

theorem n56l_xor {a b c : Nat} (ha : a ≤ 31) (hb : b ≤ 31) (hc : 31 ≤ c) :
    Exec.bitwise (· ^^ ·) a b ≤ c := n56l_bw _ rfl ha hb hc

theorem n56l_and {a b c : Nat} (ha : a ≤ 31) (hb : b ≤ 31) (hc : 31 ≤ c) :
    Exec.bitwise (· && ·) a b ≤ c := n56l_bw _ rfl ha hb hc

/-- Closes a bound goal on a value built from bounded registers by ifs, `%`, `+` and bitwise ops. -/
macro "n56l_bnd" : tactic =>
  `(tactic| repeat' (first | omega | with_reducible rfl | with_reducible apply n56l_ofNat | with_reducible apply n56l_ite |
    with_reducible apply n56l_or | with_reducible apply n56l_xor |
    with_reducible apply n56l_and | with_reducible apply n56l_mod | with_reducible apply n56l_add))
'''

def chunk(k):
    i0, i1 = cuts[k], cuts[k + 1]
    s, e, n = pcs[i0], pcs[i1], i1 - i0
    bin_, bout = bnds[i0], bnds[i1]
    last = (k == len(cuts) - 2)
    st = [x for x in stores if s <= x[0] < e]
    fr = max((o + 8 for _, o in st), default=0)
    regs = "ω'[1] = ω[1]"
    if last:
        regs += " ∧ ω'[7] = UInt64.ofNat (sp + 200) ∧ ω'[8] = ω[7] ∧ ω'[5] = ω[7]"
    else:
        regs += " ∧ ω'[7] = ω[7]"
    nreg = regs.count('∧') + 1 + len(bout)
    mem = f"(∀ c, c < 4294967296 → (c < sp ∨ sp + {fr} ≤ c) → μ'.read c = μ.read c)" if fr else \
        "(∀ c, μ'.read c = μ.read c)"
    memref = "fun c hc0 hc1 => ?_" if fr else "fun c => ?_"
    return f'''
/-- Instructions {i0}–{i1 - 1} of the stretch: from {s} to {e}. -/
theorem n56l_{k} {{p : ByteArray}} {{P : Program}} [HasCode p P] [HasCodeF p P] (x : X) (ω : Regs) (μ : Memory)
    (sp : Nat) (hsp : 65536 ≤ sp ∧ sp + 200 < 4294967296) (h1 : ω[1] = UInt64.ofNat sp)
    (hw : ∀ c, sp ≤ c → c < sp + 200 → μ.writable c = true){hyps(bin_, 'b')} :
    ∃ ω' μ', FreeStepsH p R {s} ω μ x {e} ω' μ' x {n} ∧
      {regs}{concl(bout)} ∧
      {mem} ∧
      (∀ c, μ'.readable c = μ.readable c) ∧ (∀ c, μ'.writable c = μ.writable c) := by
  have hr : ∀ c, sp ≤ c → c < sp + 200 → μ.readable c = true := fun c h1 h2 => Memory.readable_of_writable (hw c h1 h2)
  rw [show ω = regsNF ω [] from rfl]
  refine ⟨?_, ?_, ?_, ?_⟩
  rotate_left 2
  · pvm_go [h1, hsp, hw, hr, rdN_writeN_disjoint, rdN_writeN_same8, ↓rdN_fold]
  · refine ⟨{', '.join(['?_'] * nreg)}, {memref}, fun c => ?_, fun c => ?_⟩
    all_goals first
      | (simp only [PVM.getElem_regsNF, PVM.lookup_cons_nat, Nat.reduceEqDiff, ↓reduceIte, PVM.getD_some',
          List.lookup_nil, Option.getD_none]; n56l_bnd; done)
      | post_simp [rdN_writeN_disjoint, h1]
'''

def compose():
    K = len(cuts) - 1
    total = cuts[-1]
    lines = []
    lines.append(f'''
/-- **56340's length computation** (56921 → 57327, {total} steps): from any registers but ω₁ = sp,
    with the frame [sp, sp + 200) writable, it reaches the call of `from_utf8` with ω₉ ≤ 32, ω₇ =
    sp + 200, ω₈ = ω₅ = the entry ω₇, ω₁ kept; it writes only sp … sp + 16. -/
theorem n56_len {{p : ByteArray}} {{P : Program}} [HasCode p P] [HasCodeF p P] (x : X) (ω : Regs) (μ : Memory)
    (sp : Nat) (hsp : 65536 ≤ sp ∧ sp + 200 < 4294967296) (h1 : ω[1] = UInt64.ofNat sp)
    (hw : ∀ c, sp ≤ c → c < sp + 200 → μ.writable c = true) :
    ∃ ω' μ', FreeStepsH p R {START} ω μ x {END} ω' μ' x {total} ∧
      ω'[1] = ω[1] ∧ ω'[7] = UInt64.ofNat (sp + 200) ∧ ω'[8] = ω[7] ∧ ω'[5] = ω[7] ∧ ω'[9].toNat ≤ 32 ∧
      (∀ c, c < 4294967296 → (c < sp ∨ sp + 16 ≤ c) → μ'.read c = μ.read c) ∧
      (∀ c, μ'.readable c = μ.readable c) ∧ (∀ c, μ'.writable c = μ.writable c) := by''')
    # chain: obtain each chunk's result
    prev_w, prev_m = 'ω', 'μ'
    hw = 'hw'
    h1 = 'h1'
    h7 = None
    for k in range(K):
        bin_ = bnds[cuts[k]]
        bargs = ' '.join(f'b{k}_{r}' for r in sorted(bin_))
        args = f'(p := p) (P := P) (R := R) x {prev_w} {prev_m} sp hsp {h1} {hw}' + (' ' + bargs if bargs else '')
        bout = bnds[cuts[k + 1]]
        last = (k == K - 1)
        regn = ['e1'] + (['e7', 'e8', 'e5'] if last else ['e7'])
        bnames = [f'b{k+1}_{r}' for r in sorted(bout)]
        mem = ['fr', 'rd', 'wr']
        pat = ', '.join([f'r{k}'] + [f'{n}{k}' for n in regn] + bnames + [f'{n}{k}' for n in mem])
        lines.append(f'  obtain ⟨ω{k+1}, μ{k+1}, {pat}⟩ := n56l_{k} {args}')
        lines.append(f'  have h1_{k+1} : ω{k+1}[1] = UInt64.ofNat sp := by rw [e1{k}]; exact {h1}')
        lines.append(f'  have hw{k+1} : ∀ c, sp ≤ c → c < sp + 200 → μ{k+1}.writable c = true := fun c a b => by rw [wr{k}]; exact {hw} c a b')
        if not last:
            lines.append(f'  have h7_{k+1} : ω{k+1}[7] = ω[7] := by rw [e7{k}]' + (f'; exact h7_{k}' if k > 0 else ''))
        prev_w, prev_m, hw, h1 = f'ω{k+1}', f'μ{k+1}', f'hw{k+1}', f'h1_{k+1}'
    K1 = K
    run = 'r0'
    for k in range(1, K): run = f'({run}.trans r{k})'
    lines.append(f'  refine ⟨ω{K1}, μ{K1}, {run}, ?_, e7{K1-1}, ?_, ?_, b{K1}_9, ?_, ?_, ?_⟩')
    lines.append(f'  · rw [h1_{K1}, h1]')
    lines.append(f'  · rw [e8{K1-1}, h7_{K1-1}]')
    lines.append(f'  · rw [e5{K1-1}, h7_{K1-1}]')
    # memory: chunk 0 has the frame; later chunks keep everything
    later = ''.join(f'(fr{k} c).trans <| ' for k in range(K - 1, 0, -1))
    lines.append(f'  · intro c hc0 hc1; exact {later}fr0 c hc0 hc1')
    rds = ''.join(f'(rd{k} c).trans <| ' for k in range(K - 1, 0, -1))
    wrs = ''.join(f'(wr{k} c).trans <| ' for k in range(K - 1, 0, -1))
    lines.append(f'  · intro c; exact {rds}rd0 c')
    lines.append(f'  · intro c; exact {wrs}wr0 c')
    return '\n'.join(lines) + '\n'

out = hdr + ''.join(chunk(k) for k in range(len(cuts) - 1)) + compose() + '\nend Services.Bootstrap.Fmt\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'N56Len.lean'), 'w').write(out)
print(cuts, stores, bnds[N])
