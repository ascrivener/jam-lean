#!/usr/bin/env python3
"""Write `Services/Bootstrap/AccLog/<Name>.lean`: a frame-only summary of one accumulate log site,
`format!` (59375) at `site`, then `log` (100, level 2) and the `String`'s dealloc (40613), from the
template `AccLog/Imported.lean` (itself `ItemLog.lean` at 9116's addresses).

usage: gen_acc_log_site.py Name site ret str args tmpl "doc text"
  site  pc of the `format!` call (loadImmJump 0 ret 59375); ret its return-table value
  str   the String's offset from sp (ω₇ = sp + str); args the argument pairs' offset (ω₉)
  tmpl  the template's address (its octets are read from the blob)
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BLOB = os.path.join(ROOT, 'services/bootstrap/jam-bootstrap-service.jam')
RO = 65444

def items(T):
    b = open(BLOB, 'rb').read()
    i = T - RO; out = []
    while True:
        c = b[i]
        if c == 0:
            i += 1; break
        if c == 192:
            out.append(('arg', None)); i += 1; continue
        assert 1 <= c < 128, c
        out.append(('lit', c)); i += 1 + c
    return out, list(b[T - RO:i])

def main():
    name, site, ret, st, args, T, doc = sys.argv[1:8]
    site, ret, st, args, T = map(int, (site, ret, st, args, T))
    its, by = items(T)
    n = len(by)
    src = open(os.path.join(ROOT, 'Services/Bootstrap/AccLog/Imported.lean')).read()
    low = name[0].lower() + name[1:]
    # template proof
    o = 0; pf = []
    for k, v in its:
        if k == 'lit':
            pf.append(f'  refine ⟨by decide, by decide, (r {o} (by decide)).trans (by decide), fun b h1 h2 => hr b (by omega) (by omega), ?_⟩')
            o += 1 + v
        else:
            pf.append(f'  refine ⟨(r {o} (by decide)).trans (by decide), hr _ (by omega) (by omega), ?_⟩')
            o += 1
    pf.append(f'  exact ⟨(r {o} (by decide)).trans (by decide), hr _ (by omega) (by omega)⟩')
    tl = ', '.join(f'.lit {v}' if k == 'lit' else '.arg' for k, v in its)
    m = re.search(r'(  have r := fun j hj => rd1_of_readN h j hj\n  simp only \[importedTmpl, Tmpl\]\n)(.*?)(\n\nvariable)', src, re.S)
    src = src[:m.start(2)] + '\n'.join(pf) + src[m.end(2):]
    src = re.sub(r'def importedTmplBytes : List UInt8 := \[.*?\]\n', f'def importedTmplBytes : List UInt8 := {by}\n'.replace("'", ''), src, flags=re.S)
    src = src.replace('def importedTmpl : List TItem := [.lit 14, .arg]', f'def importedTmpl : List TItem := [{tl}]')
    src = src.replace('import Services.Bootstrap.AccLog.ItemLog', 'import Services.Bootstrap.AccLog.Imported')
    # numbers; String offsets first (longest first to avoid clashes)
    rep = {'1592': str(st + 24), '1584': str(st + 16), '1576': str(st + 8), '1568': str(st),
           '1496': str(args), '66312': str(T), '66329': str(T + n), '66312 17': f'{T} {n}',
           '9116': str(site), '9123': str(site + 7), '9142': str(site + 26), '9144': str(site + 28),
           '9146': str(site + 30), '9151': str(site + 35), '9159': str(site + 43), '9165': str(site + 49),
           '314': str(ret), '316': str(ret + 2), 'jte_156': f'jte_{ret // 2 - 1}', 'jte_157': f'jte_{ret // 2}'}
    keys = sorted(rep, key=len, reverse=True)
    pat = re.compile('|'.join(r'(?<![0-9])' + re.escape(k) + r'(?![0-9])' for k in keys))
    src = pat.sub(lambda m: rep[m.group(0)], src)
    src = re.sub(rf'/-- The template at {T}: .*?-/', f'/-- The template at {T}: {doc}. -/', src)
    src = src.replace("The template's 17 octets", f"The template's {n} octets")
    src = re.sub(r'/-!.*?-/', f'''/-!
# The `{name}` handler's log line ({site} … {site + 49}), frame-only

`format!` at {site} (`format_inner`, 59375; template at {T}, its argument pairs at sp + {args}) writes a
`String` at sp + {st}; `log` (100, level 2) at {site + 28} sends it (the message unspecified), and the
`String` is freed at {site + 43} (40613). Generated by `scripts/gen_acc_log_site.py` from
`Imported.lean`; the arguments' formatting is the hypothesis `hA`.
-/''', src, count=1, flags=re.S)
    src = src.replace('importedTmplBytes', low + 'TmplBytes').replace('importedTmpl', low + 'Tmpl')
    src = src.replace('tmpl_imported', 'tmpl_' + low).replace('imported_', low + '_').replace('iml_', low[:3] + '_')
    src = src.replace('/-- Imported', f'/-- {name}')
    out = os.path.join(ROOT, f'Services/Bootstrap/AccLog/{name}.lean')
    open(out, 'w').write(src)
    print('wrote', out)

main()
